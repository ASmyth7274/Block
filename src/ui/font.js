const FONT_COLORS = {
  '0': '#000000', '1': '#0000aa', '2': '#00aa00', '3': '#00aaaa', '4': '#aa0000', '5': '#aa00aa', '6': '#ffaa00', '7': '#aaaaaa',
  '8': '#555555', '9': '#5555ff', 'a': '#55ff55', 'b': '#55ffff', 'c': '#ff5555', 'd': '#ff55ff', 'e': '#ffff55', 'f': '#ffffff',
};

class PixelFont {
  constructor() {
    this.cells = {};       // char -> index in atlas
    this.atlas = document.createElement('canvas');
    const chars = Object.keys(GLYPHS);
    this.cols = 16;
    this.atlas.width = 16 * 8; this.atlas.height = Math.ceil(chars.length / 16) * 8;
    const ctx = this.atlas.getContext('2d');
    const img = ctx.createImageData(this.atlas.width, this.atlas.height);
    chars.forEach((ch, i) => {
      this.cells[ch] = i;
      const gl = GLYPHS[ch], ox = (i % 16) * 8, oy = Math.floor(i / 16) * 8;
      gl.rows.forEach((row, ry) => {
        for (let rx = 0; rx < row.length; rx++) if (row[rx] === '#') {
          const p = ((oy + gl.top + ry) * this.atlas.width + ox + rx) * 4;
          img.data[p] = 255; img.data[p + 1] = 255; img.data[p + 2] = 255; img.data[p + 3] = 255;
        }
      });
    });
    ctx.putImageData(img, 0, 0);
    this.tinted = new Map();
    this.lineHeight = 9;
  }
  atlasFor(color) {
    let c = this.tinted.get(color);
    if (c) return c;
    c = document.createElement('canvas');
    c.width = this.atlas.width; c.height = this.atlas.height;
    const ctx = c.getContext('2d');
    ctx.drawImage(this.atlas, 0, 0);
    ctx.globalCompositeOperation = 'source-in';
    ctx.fillStyle = color;
    ctx.fillRect(0, 0, c.width, c.height);
    this.tinted.set(color, c);
    return c;
  }
  charWidth(ch) { const g = GLYPHS[ch] || GLYPHS['?']; return g.w + 1; }
  width(str) {
    let w = 0;
    for (let i = 0; i < str.length; i++) {
      const ch = str[i];
      if (ch === '§') { i++; continue; }
      w += this.charWidth(ch);
    }
    return Math.max(0, w - 1);
  }
  // draw text at GUI-unit coordinates; ctx already scaled to GUI units
  draw(ctx, str, x, y, color, shadow) {
    str = String(str);
    color = color || '#ffffff';
    if (shadow !== false) this.drawRaw(ctx, str, x + 1, y + 1, color, true);
    return this.drawRaw(ctx, str, x, y, color, false);
  }
  drawRaw(ctx, str, x, y, color, isShadow) {
    let cx = Math.round(x);
    const iy = Math.round(y);
    let cur = color;
    let atlas = this.atlasFor(isShadow ? shadowOf(cur) : cur);
    for (let i = 0; i < str.length; i++) {
      const ch = str[i];
      if (ch === '§' && i + 1 < str.length) {
        const code = str[++i].toLowerCase();
        cur = FONT_COLORS[code] || (code === 'r' ? color : cur);
        atlas = this.atlasFor(isShadow ? shadowOf(cur) : cur);
        continue;
      }
      let idx = this.cells[ch];
      if (idx === undefined) idx = this.cells['?'];
      const g = GLYPHS[ch] || GLYPHS['?'];
      if (ch !== ' ') ctx.drawImage(atlas, (idx % 16) * 8, Math.floor(idx / 16) * 8, 8, 8, cx, iy, 8, 8);
      cx += g.w + 1;
    }
    return cx;
  }
  // word-wrap into lines no wider than maxW
  wrap(str, maxW) {
    const out = [];
    for (const para of String(str).split('\n')) {
      const words = para.split(' ');
      let line = '';
      for (const w of words) {
        const t = line ? line + ' ' + w : w;
        if (this.width(t) > maxW && line) { out.push(line); line = w; } else line = t;
      }
      out.push(line);
    }
    return out;
  }
}
function shadowOf(hex) {
  const c = hexToRgb(hex);
  return rgbToHex(c[0] >> 2, c[1] >> 2, c[2] >> 2);
}
